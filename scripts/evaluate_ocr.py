"""Evaluate offline OCR on deterministic synthetic nameplates."""
import io
import json
import statistics
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from backend import nameplate
from scripts.generate_nameplates import VARIANTS, render_nameplate


def summarize(samples):
  return {'top1_accuracy':round(sum(s['correct'] for s in samples)/len(samples),4),
          'auto_open_rate':round(sum(s['decision']=='auto' for s in samples)/len(samples),4),
          'wrong_auto_open':sum(s['decision']=='auto' and not s['correct'] for s in samples),
          'median_ms':round(statistics.median(s['elapsed_ms'] for s in samples),1)}


def main():
  machineIds=[f'CNC-{number:02}' for number in range(1,19)]
  nameplate.warmup()
  allSamples=[]
  byVariant={}
  for variant in VARIANTS:
    samples=[]
    for machineId in machineIds:
      buffer=io.BytesIO()
      render_nameplate(machineId,variant).save(buffer,'PNG')
      started=time.perf_counter()
      lines=nameplate.recognize(buffer.getvalue())
      candidates=nameplate.match_machine_ids(lines,machineIds)
      samples.append({'machine_id':machineId,'variant':variant,
                      'predicted':candidates[0]['machine_id'] if candidates else None,
                      'correct':bool(candidates and candidates[0]['machine_id']==machineId),
                      'decision':nameplate.decide(candidates),
                      'elapsed_ms':round((time.perf_counter()-started)*1000,1)})
    allSamples.extend(samples)
    byVariant[variant]=summarize(samples)
    print(variant,json.dumps(byVariant[variant]),flush=True)
  report={'dataset':'synthetic nameplates generated by scripts/generate_nameplates.py',
          'is_synthetic':True,'engine':nameplate.engine_info(),
          'generated_at':datetime.now(timezone.utc).isoformat(),'samples_per_variant':18,
          'by_variant':byVariant,'overall':summarize(allSamples),'samples':allSamples}
  output=ROOT/'artifacts'/'ocr-eval-report.json'
  output.write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
  return 0 if byVariant['clean']['top1_accuracy']==1 and report['overall']['wrong_auto_open']==0 else 1


if __name__=='__main__':
  raise SystemExit(main())
